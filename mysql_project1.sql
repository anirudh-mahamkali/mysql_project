DROP DATABASE IF EXISTS MYSQL_PROJECT;
CREATE DATABASE MYSQL_PROJECT;
USE MYSQL_PROJECT;

CREATE TABLE THEATERS_AND_MOVIES(
    SCHEDULE_ID INT AUTO_INCREMENT PRIMARY KEY,
    THEATER_NAME VARCHAR(100) NOT NULL, -- name of the theater 
    THEATER_LOCATION VARCHAR(100) NOT NULL, -- address of the theater 
    MOVIE_NAME VARCHAR(50) NOT NULL, -- name of particular movie
    SHOW_TIMINGS VARCHAR(10) NOT NULL, -- particular show timings 
    SCREEN_NUMBER VARCHAR(10) NOT NULL, -- particular screen number like screen 1 or 2 
    TICKET_COST INT NOT NULL
);

CREATE TABLE MOVIETICKET_BOOKING_ENGINE(
    BOOKING_ID INT AUTO_INCREMENT PRIMARY KEY,
    CUSTOMER_NAME VARCHAR(100) NOT NULL, -- name of customer booking ticket
    SCHEDULE_ID INT NOT NULL, -- schedule_id mean the id scheduled for that movie
    SEAT_NUMBER INT NOT NULL, -- particular seat number 20 or 18 or 15 or anything 
    PAYEMENT_METHOD VARCHAR(20) NOT NULL, -- payement_methodn either upi or cash 
    APPLY_OFFERS VARCHAR(20) NOT NULL, -- offers like dusshera or diwali offers or cuopns 
    BOOKING_STATUS VARCHAR(30) DEFAULT 'BOOKED', --  status of booking of ticket 
    FOREIGN KEY (SCHEDULE_ID) REFERENCES THEATERS_AND_MOVIES(SCHEDULE_ID) -- foregin key is a constraint which links parent and child tables 
);

